"""MCC / MC/DC generator for BR-2 (adjustability decision of StockAdjustmentItemSerializer.validate_pk).

Decision under test (from the requirement BR-2, written independently of the code):
    REJECT = (not ALLOW) and (SO or BT or CU or CB)
  ALLOW = global setting STOCK_ALLOW_OUT_OF_STOCK_TRANSFER is true
  SO / BT / CU / CB = sales_order / belongs_to / customer / consumed_by is set (not None)
Usage: python tools/mcdc.py > docs/MCC_MCDC.md
"""
from itertools import combinations, product

CONDITIONS = ['ALLOW', 'SO', 'BT', 'CU', 'CB']


def decision(row):
    allow, so, bt, cu, cb = row
    return (not allow) and (so or bt or cu or cb)


def truth_table():
    return [(i + 1, row, bool(decision(row))) for i, row in enumerate(product([False, True], repeat=len(CONDITIONS)))]


def independence_pairs(table):
    """For each condition: pairs of rows differing ONLY in that condition with different outcomes (unique-cause MC/DC)."""
    by_row = {row: (i, out) for i, row, out in table}
    pairs = {c: [] for c in CONDITIONS}
    for k, c in enumerate(CONDITIONS):
        for row, (i, out) in by_row.items():
            if row[k]:
                continue
            flipped = row[:k] + (True,) + row[k + 1:]
            j, out2 = by_row[flipped]
            if out != out2:
                pairs[c].append((i, j))
    return pairs


def minimal_mcdc_set(table):
    """Smallest set of rows (n+1 = 6 expected) that contains an independence pair for every condition."""
    pairs = independence_pairs(table)
    ids = [i for i, _, _ in table]
    for size in range(len(CONDITIONS) + 1, len(ids) + 1):
        for subset in combinations(ids, size):
            s = set(subset)
            if all(any(a in s and b in s for a, b in pairs[c]) for c in CONDITIONS):
                return sorted(subset), {c: next((a, b) for a, b in pairs[c] if a in s and b in s) for c in CONDITIONS}
    raise RuntimeError('no MC/DC set')


def main():
    t = truth_table()
    pairs = independence_pairs(t)
    mset, chosen = minimal_mcdc_set(t)
    print('# MCC and MC/DC for BR-2 (`validate_pk`) — generated by `tools/mcdc.py`\n')
    print('Decision: `REJECT = (not ALLOW) and (SO or BT or CU or CB)`; ALLOW = setting `STOCK_ALLOW_OUT_OF_STOCK_TRANSFER`; SO/BT/CU/CB = sales_order / belongs_to / customer / consumed_by set.\n')
    print('## Complete multiple-condition coverage (MCC): all 2^5 = 32 combinations\n')
    print('| # | ALLOW | SO | BT | CU | CB | REJECT (expected) | MC/DC set |\n|---|---|---|---|---|---|---|---|')
    for i, row, out in t:
        print(f"| {i} | " + ' | '.join('T' if v else 'F' for v in row) + f" | {'reject' if out else 'accept'} | {'✔' if i in mset else ''} |")
    print('\n## MC/DC independence pairs (rows differing only in the named condition, different outcome)\n')
    print('| Condition | All pairs (row,row) | Pair chosen in the minimal set |\n|---|---|---|')
    for c in CONDITIONS:
        print(f"| {c} | {', '.join(f'({a},{b})' for a, b in pairs[c])} | {chosen[c]} |")
    print(f"\nMinimal MC/DC set: rows {mset} ({len(mset)} tests = n+1 for n = {len(CONDITIONS)} conditions).")


if __name__ == '__main__':
    main()
