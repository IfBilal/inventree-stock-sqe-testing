"""Per-function statement and branch coverage for the in-scope business logic (TEST_BASIS §7).
Input: coverage.py JSON (`coverage json --show-contexts` not needed). Exit code 1 if any in-scope function is < 100 % (unless justified in docs/COVERAGE_JUSTIFICATION.md).
Usage: python tools/scope_coverage.py evidence/coverage/coverage.json [--md docs/COVERAGE_SCOPE.md]"""
import ast, json, sys, os

BASE = 'upstream/src/backend/InvenTree/'
SCOPE = {
    'stock/serializers.py': ['StockAdjustmentItemSerializer.__init__', 'StockAdjustmentItemSerializer.validate_pk',
                             'StockAdjustmentItemSerializer.validate_quantity', 'StockAdjustmentSerializer.to_internal_value',
                             'StockAdjustmentSerializer.validate', 'StockAddSerializer.save', 'StockRemoveSerializer.save'],
    'stock/models.py': ['StockItem.is_in_stock', 'StockItem.lock_quantity', 'StockItem.updateQuantity', 'StockItem.add_stock',
                        'StockItem.take_stock', 'StockItem.optional_transfer_fields', 'StockItem.model_reference_fields',
                        'StockItem._apply_model_reference_fields', 'StockItem._resolve_status_kwarg',
                        'StockItem._apply_status_change', 'StockItem._apply_optional_transfer_fields',
                        'StockItem.can_delete', 'StockItem.installed_item_count', 'StockItem.save', 'StockItem.delete', 'StockItem.tracking_event',
                        'StockItem._tracking_deltas', 'StockItem._audit_deltas', 'StockItem._is_empty_tracking_event'],
    'stock/api.py': ['StockAdjustView.get_serializer_context'],
    'InvenTree/fields.py': ['PrefetchedPrimaryKeyRelatedField.__init__', 'PrefetchedPrimaryKeyRelatedField.to_internal_value'],
    'InvenTree/permissions.py': ['ModelPermission._queryset', 'RolePermission.has_permission'],
}


# Uncovered branches that are defended in docs/COVERAGE_JUSTIFICATION.md (key: file, function, branch source line, target line)
JUSTIFIED = {('InvenTree/permissions.py', 'ModelPermission._queryset', 227, 230):
             "DRF's parent _queryset() asserts queryset is not None, so the 'None' branch is unreachable (defensive)."}


def function_ranges(path):
    tree = ast.parse(open(path).read())
    out = {}
    for cls in [n for n in tree.body if isinstance(n, ast.ClassDef)]:
        for fn in [n for n in cls.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))]:
            out[f'{cls.name}.{fn.name}'] = (fn.lineno, fn.end_lineno)
    return out


def main(cov_json, md=None):
    data = json.load(open(cov_json))
    files = {k: v for k, v in data['files'].items()}
    rows, ok = [], True
    for fname, funcs in SCOPE.items():
        key = next(k for k in files if k.endswith('/' + fname))
        cov = files[key]
        ranges = function_ranges(BASE + fname)
        executed, missing = set(cov['executed_lines']), set(cov['missing_lines'])
        ex_br = cov.get('executed_branches', []); mi_br = cov.get('missing_branches', [])
        for f in funcs:
            lo, hi = ranges[f]
            stm_total = len([l for l in executed | missing if lo <= l <= hi])
            stm_miss = sorted(l for l in missing if lo <= l <= hi)
            br_total = len([b for b in ex_br + mi_br if lo <= b[0] <= hi])
            br_miss_all = [tuple(b) for b in mi_br if lo <= b[0] <= hi]
            br_just = [b for b in br_miss_all if (fname, f, b[0], b[1]) in JUSTIFIED]
            br_miss = [b for b in br_miss_all if b not in br_just]
            sp = 100.0 if stm_total == 0 else 100.0 * (stm_total - len(stm_miss)) / stm_total
            bp = 100.0 if br_total == 0 else 100.0 * (br_total - len(br_miss_all)) / br_total   # raw branch % (justified misses still counted as missed)
            rows.append((fname, f, lo, hi, stm_total, len(stm_miss), sp, br_total, len(br_miss_all), bp, stm_miss, [f'{b} JUSTIFIED' for b in br_just] + br_miss))
            if stm_miss or br_miss:
                ok = False
    lines = ['# In-scope coverage (per function) — generated by `tools/scope_coverage.py`\n',
             '| File | Function | Lines | Statements | Missed | Stmt % | Branches | Missed | Branch % | Missing lines / branches |', '|---|---|---|---|---|---|---|---|---|---|']
    for r in rows:
        lines.append(f'| {r[0]} | `{r[1]}` | {r[2]}-{r[3]} | {r[4]} | {r[5]} | {r[6]:.0f} | {r[7]} | {r[8]} | {r[9]:.0f} | {r[10] or ""} {r[11] or ""} |')
    ts = sum(r[4] for r in rows); tm = sum(r[5] for r in rows); tb = sum(r[7] for r in rows); tbm = sum(r[8] for r in rows)
    lines.append(f'\n**Total in scope:** statements {ts - tm}/{ts} ({100 * (ts - tm) / ts:.1f} %), branches {tb - tbm}/{tb} ({100 * (tb - tbm) / tb:.1f} %). Uncovered branches: {tbm}, of which defended in `docs/COVERAGE_JUSTIFICATION.md`: {sum(1 for r in rows for x in r[11] if str(x).endswith("JUSTIFIED"))}; **unjustified: {sum(1 for r in rows for x in r[11] if not str(x).endswith("JUSTIFIED"))}**.')
    text = '\n'.join(lines)
    print(text)
    if md:
        open(md, 'w').write(text + '\n')
    sys.exit(0 if ok else 1)


if __name__ == '__main__':
    args = sys.argv[1:]
    main(args[0], args[args.index('--md') + 1] if '--md' in args else None)
