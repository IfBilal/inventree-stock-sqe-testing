#!/usr/bin/env python3
"""Generate docs/TRACEABILITY.md from evidence/traceability/*.json (outcomes + req markers recorded by tests/team/conftest.py)."""
import glob, json, os, collections
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
REQS = [  # id, workflow, description, source, risks, planned
 ('FR-01', 'A', 'add N → quantity +N', 'DOC+CODE', 'PR-01'), ('FR-02', 'A', 'add records history', 'CODE', 'PR-07'),
 ('FR-03a', 'A', 'negative/non-numeric/over-precision rejected', 'CODE', 'PR-04'), ('FR-03b', 'A', 'zero rejected (A-2, DEF-02)', 'ASSUMPTION', 'PR-04'),
 ('FR-04', 'A', 'non-adjustable item rejected', 'CODE', 'PR-03'), ('FR-05', 'B', 'remove N ≤ available → −N', 'DOC+CODE', 'PR-01'),
 ('FR-06', 'B', 'remove records history', 'CODE', 'PR-07'), ('FR-07', 'B', 'remove > available rejected (A-1, DEF-01)', 'ASSUMPTION', 'PR-01'),
 ('FR-08', 'B', 'removing all depletes the item', 'CODE', 'PR-01'), ('FR-09', 'A,B', 'role without add right → 403', 'CODE', 'PR-02'),
 ('FR-10', 'A,B', 'multi-item request atomic', 'CODE', 'PR-05'), ('FR-11', 'A,B', 'serialized item unchanged', 'CODE', 'PR-05'),
 ('BR-1', 'A,B', 'boundary: 0 < N ≤ limit / ≤ available / result representable', 'CODE+A-1', 'PR-01, PR-04'),
 ('BR-2', 'A,B', 'adjustability decision (5 conditions)', 'CODE', 'PR-03'), ('BR-3', 'B/A', 'state change: deplete / restock', 'CODE', 'PR-01'),
 ('BR-4', 'A,B', 'role permission', 'CODE', 'PR-02')]
rows = []
for f in glob.glob(os.path.join(ROOT, 'evidence/traceability/*.json')):
    lvl = os.path.basename(f)[:-5]
    for r in json.load(open(f)):
        rows.append({**r, 'level': lvl})
# E2E: results come from the Playwright JSON report (reports/playwright-report.json); the requirements of a test follow from its use case (docs/USE_CASES.md)
UC_REQ = {'UC01': ['FR-01', 'FR-02', 'FR-03a', 'BR-1'], 'UC02': ['FR-05', 'FR-06', 'FR-07', 'BR-1'], 'UC03': ['FR-08', 'BR-3'], 'UC04': ['BR-3', 'BR-1', 'FR-01'],
          'UC05': ['BR-4', 'FR-09'], 'UC06': ['FR-03a', 'FR-07', 'BR-1']}
PW = os.path.join(ROOT, 'reports/playwright-report.json')
if os.path.exists(PW):
    def walk(suite):
        for sp in suite.get('specs', []):
            for t in sp['tests']:
                yield sp['title'], t
        for c in suite.get('suites', []):
            yield from walk(c)
    for st in json.load(open(PW))['suites']:
        for title, t in walk(st):
            uc = title.split()[0].split('-')[0]
            if uc not in UC_REQ: continue
            ok = t['status'] == 'expected'
            rows.append({'id': 'e2e/' + title[:90], 'outcome': ('passed' if t['expectedStatus'] == 'passed' else 'xfailed') if ok else 'failed', 'req': UC_REQ[uc], 'risk': [], 'seq': [], 'level': 'e2e'})
by_req = collections.defaultdict(list)
for r in rows:
    for q in r['req']:
        by_req[q].append(r)
out = ['# TRACEABILITY MATRIX — generated by `tools/gen_traceability.py` from `evidence/traceability/*.json` (test outcomes + `@pytest.mark.req` tags)\n',
       'Test levels: `unit` (tests/team/unit), `api` (tests/team/api, live HTTP), `e2e` (tests/team/e2e, Playwright). "Verified" = ≥ 1 passing test asserting the requirement. "Defect found" = the requirement\'s expected behaviour is asserted by a strict-xfail test that fails on the baseline (the strict-xfail tests that remain are documented weaknesses W-08/W-09/W-12 of the upstream API, see `docs/API_TESTING.md`; the defects DEF-01…04 are fixed). ',
       'Requirement coverage (tested) = requirements with ≥ 1 executed test ÷ 16. Requirement coverage (verified) = requirements with ≥ 1 passing test ÷ 16.\n',
       '| Req | Workflow | Description | Source | Risk | unit (pass/xfail) | api (pass/xfail) | e2e (pass/xfail) | Example test ids | Status |', '|---|---|---|---|---|---|---|---|---|---|']
tested = verified = 0
for rid, wf, desc, src, risk in REQS:
    rs = by_req.get(rid, [])
    cnt = {lv: [sum(1 for r in rs if r['level'] == lv and r['outcome'] == 'passed'), sum(1 for r in rs if r['level'] == lv and r['outcome'] == 'xfailed')] for lv in ('unit', 'api', 'e2e')}
    npass = sum(c[0] for c in cnt.values()); nxf = sum(c[1] for c in cnt.values())
    status = 'verified' + (' + defect found' if nxf else '') if npass else ('defect found (expected behaviour fails on baseline)' if nxf else 'untested')
    tested += bool(npass or nxf); verified += bool(npass)
    ex = [r['id'].split('::')[-1][:44] for r in rs if r['outcome'] == 'passed'][:2]
    out.append(f'| {rid} | {wf} | {desc} | {src} | {risk} | {cnt["unit"][0]}/{cnt["unit"][1]} | {cnt["api"][0]}/{cnt["api"][1]} | {cnt["e2e"][0]}/{cnt["e2e"][1]} | {"; ".join("`"+e+"`" for e in ex)} | {status} |')
out.append(f'\n**Requirements coverage — tested: {tested} / {len(REQS)} ({100*tested/len(REQS):.0f} %); verified passing: {verified} / {len(REQS)} ({100*verified/len(REQS):.0f} %).**')
tot = collections.Counter((r['level'], r['outcome']) for r in rows)
out.append('\n## Test inventory by level and outcome\n| Level | passed | xfailed (defect) | skipped | failed | total |\n|---|---|---|---|---|---|')
for lv in sorted({r['level'] for r in rows}):
    g = lambda o: tot.get((lv, o), 0)
    out.append(f"| {lv} | {g('passed')} | {g('xfailed')} | {g('skipped')} | {g('failed')} | {sum(v for (l, _), v in tot.items() if l == lv)} |")
print('\n'.join(out))
