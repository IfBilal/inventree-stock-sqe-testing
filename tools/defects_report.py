#!/usr/bin/env python3
"""Defect log + Pareto by category (count and severity-weighted) from docs/defects.json -> docs/DEFECTS.md and docs/pareto_defects.svg"""
import collections, json, os
R = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
D = json.load(open(os.path.join(R, 'docs/defects.json')))
URL = 'https://github.com/IfBilal/inventree-stock-sqe-testing/issues/'
W = {'Critical': 5, 'High': 4, 'Medium': 3, 'Low': 1}
cnt = collections.Counter(d['category'] for d in D)
wt = collections.Counter()
for d in D: wt[d['category']] += W[d['severity']]
order = sorted(cnt, key=lambda c: (-wt[c], c))
total = sum(wt.values()); cum = 0
out = ['# DEFECT LOG, TRIAGE AND PARETO ANALYSIS (generated by `tools/defects_report.py` from `docs/defects.json`)\n',
       f'Defects live in **GitHub Issues of this repository** ({URL[:-8]}) — never upstream. Severity: Critical (data loss/corruption, whole-feature outage), High (availability under normal use), Medium, Low. Priority P1 = fix first … P3 = later. Weights for the Pareto: Critical 5, High 4, Medium 3, Low 1.\n',
       '| ID | Issue | Title | Category | Severity | Priority | Status | Triage decision | Risk | Found in |\n|---|---|---|---|---|---|---|---|---|---|']
for d in D:
    out.append(f"| {d['id']} | [#{d['issue']}]({URL}{d['issue']}) | {d['title']} | {d['category']} | {d['severity']} | {d['priority']} | {d['status']} | accepted | {d['risk']} | {d['found']} |")
out.append('\n## Lifecycle (status changes over time)\n| Defect | When | Status | Note |\n|---|---|---|---|')
for d in D:
    for h in d.get('history', []):
        out.append(f"| {d['id']} | {h['when']} | {h['status']} | {h['note']} |")
out.append('\n## Pareto by category\n| Category | Defects | Severity-weighted points | Share | Cumulative |\n|---|---|---|---|---|')
for c in order:
    cum += wt[c]
    out.append(f'| {c} | {cnt[c]} | {wt[c]} | {100 * wt[c] / total:.0f} % | {100 * cum / total:.0f} % |')
top = [c for c in order if True][:3]
out.append(f"\nThe top three categories ({', '.join(top)}) account for {100 * sum(wt[c] for c in top) / total:.0f} % of the severity-weighted defect load; **Data integrity** alone (DEF-01, DEF-03: 2 defects, both Critical) is the largest single category, which matches the risk register (PR-01 is the only Critical risk). See `pareto_defects.svg`.")
# SVG bar + cumulative line
w, h, ml, mb = 640, 340, 60, 90
bw = (w - ml - 20) / len(order)
svg = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" font-family="sans-serif" font-size="11">', f'<rect width="{w}" height="{h}" fill="white"/>',
       '<text x="10" y="18" font-size="14" font-weight="bold">Pareto of defects by category (severity-weighted)</text>']
mx = max(wt.values()); y0 = h - mb; ytop = 40
cum = 0; pts = []
for i, c in enumerate(order):
    x = ml + i * bw
    bh = (y0 - ytop) * wt[c] / mx
    svg.append(f'<rect x="{x + 6:.0f}" y="{y0 - bh:.0f}" width="{bw - 12:.0f}" height="{bh:.0f}" fill="#4c6ef5"/><text x="{x + bw / 2:.0f}" y="{y0 - bh - 4:.0f}" text-anchor="middle">{wt[c]}</text>')
    svg.append(f'<text x="{x + bw / 2:.0f}" y="{y0 + 16}" text-anchor="middle" transform="rotate(25 {x + bw / 2:.0f} {y0 + 16})">{c}</text>')
    cum += wt[c]; pts.append((x + bw / 2, y0 - (y0 - ytop) * cum / total))
svg.append('<polyline fill="none" stroke="#e03131" stroke-width="2" points="' + ' '.join(f'{x:.0f},{y:.0f}' for x, y in pts) + '"/>')
for x, y in pts: svg.append(f'<circle cx="{x:.0f}" cy="{y:.0f}" r="3" fill="#e03131"/>')
svg.append(f'<line x1="{ml}" y1="{y0}" x2="{w - 10}" y2="{y0}" stroke="#333"/><line x1="{ml}" y1="{ytop}" x2="{ml}" y2="{y0}" stroke="#333"/>')
svg.append(f'<text x="{w - 260}" y="20" font-size="10" fill="#e03131">red line: cumulative % (to 100 % at the top)</text></svg>')
open(os.path.join(R, 'docs/pareto_defects.svg'), 'w').write('\n'.join(svg))
out.append('\n![Pareto of defects by category](pareto_defects.svg)\n')
out.append('\n**GitHub issue tracker of the team repository (12 findings, 3 open):**\n\n![GitHub issues list](../evidence/screenshots/issues_list.png)\n')
print('\n'.join(out))
